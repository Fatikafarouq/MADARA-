"""Export the approved offline model into a compact TypeScript bundle."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--artifacts", type=Path, default=Path("artifacts"))
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    model = json.loads((args.artifacts / "xgboost_residual.json").read_text(encoding="utf-8"))
    curves = json.loads((args.artifacts / "woods_curves.json").read_text(encoding="utf-8"))
    preprocessing = json.loads((args.artifacts / "preprocessor.json").read_text(encoding="utf-8"))
    metrics = json.loads((args.artifacts / "metrics.json").read_text(encoding="utf-8"))
    learner = model["learner"]
    trees = learner["gradient_booster"]["model"]["trees"]

    bundle = {
        "version": metrics["model_version"],
        "units": "kg per day",
        "kgPerLitre": 1.03,
        "clipHighKgPerDay": metrics["clip_max"],
        "absoluteError70KgPerDay": metrics["absolute_error_70"],
        "breedCurves": curves["breed"],
        "featureOrder": preprocessing["feature_order_after_encoding"],
        "baseScore": float(learner["learner_model_param"]["base_score"]),
        "trees": [
            {
                "l": tree["left_children"],
                "r": tree["right_children"],
                "f": tree["split_indices"],
                "v": tree["split_conditions"],
                "d": tree["default_left"],
            }
            for tree in trees
        ],
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    encoded = json.dumps(bundle, separators=(",", ":"), ensure_ascii=False)
    args.output.write_text(
        "// Generated by training/export_mobile.py; do not edit manually.\n"
        f"export const MODEL_DATA = {encoded} as const;\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
